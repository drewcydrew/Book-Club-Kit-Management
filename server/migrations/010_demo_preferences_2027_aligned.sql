  CREATE OR REPLACE FUNCTION pg_temp.aligned_normal(value text) RETURNS text LANGUAGE sql IMMUTABLE AS
    $f$ SELECT regexp_replace(lower(coalesce(value, '')), '[^[:alnum:]]', '', 'g') $f$;

  -- The only baseline title missing from the catalogue; it gets the same one-kit setup as the original demo import.
  IF NOT EXISTS (SELECT 1 FROM titles WHERE pg_temp.aligned_normal(name) = 'inheritance' AND pg_temp.aligned_normal(author) = 'kathoconnor') THEN
    new_title_id := gen_random_uuid()::text;
    INSERT INTO titles (id, name, author, isbn, pages) VALUES (new_title_id, 'Inheritance', 'Kath O''Connor', '', 0);
