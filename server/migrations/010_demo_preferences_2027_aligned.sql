      INSERT INTO kits (id, title_id, branch, copies, extras) VALUES (new_kit_id, new_title_id, new_kit_branch, 10, '');
      INSERT INTO kit_identifiers (kit_id, identifier, kind) VALUES (new_kit_id, 'demo-2027-' || new_title_id, 'kit');
    END IF;
  END IF;

  CREATE TEMP TABLE aligned_club_map ON COMMIT DROP AS
  SELECT s.club, array_agg(c.id ORDER BY c.id) AS ids
  FROM (SELECT DISTINCT club FROM aligned_rows) s
  LEFT JOIN clubs c ON pg_temp.aligned_normal(c.name) = pg_temp.aligned_normal(s.club)
  GROUP BY s.club;
  SELECT string_agg(club || CASE WHEN ids[1] IS NULL THEN ' (not found)' ELSE ' (ambiguous)' END, '; ' ORDER BY club) INTO problems
  FROM aligned_club_map WHERE ids[1] IS NULL OR cardinality(ids) > 1;
  IF problems IS NOT NULL THEN RAISE EXCEPTION 'Aligned demo preferences: unresolved clubs: %', problems; END IF;

  -- Existing titles differ from the baseline by spelling, formatting or ISBN, so match in tiers and use the
  -- first tier that finds a title: ISBN; name and author; same author with a name that starts the other.
  CREATE TEMP TABLE aligned_title_candidates ON COMMIT DROP AS
  SELECT s.key, t.id AS title_id, CASE
    WHEN s.isbn <> '' AND t.isbn = s.isbn THEN 1
    WHEN pg_temp.aligned_normal(t.name) IN (pg_temp.aligned_normal(s.name), pg_temp.aligned_normal(s.source_name)) AND a.same_author THEN 2
    WHEN a.same_author AND length(pg_temp.aligned_normal(t.name)) >= 5 AND EXISTS (
      SELECT 1 FROM unnest(ARRAY[s.name, s.source_name]) AS n(value)
      WHERE length(pg_temp.aligned_normal(n.value)) >= 5
        AND (pg_temp.aligned_normal(n.value) LIKE pg_temp.aligned_normal(t.name) || '%'
          OR pg_temp.aligned_normal(t.name) LIKE pg_temp.aligned_normal(n.value) || '%')) THEN 3
  END AS tier
  FROM aligned_titles s CROSS JOIN titles t
  CROSS JOIN LATERAL (SELECT s.author = 'Unknown author' OR pg_temp.aligned_normal(t.author) IN (pg_temp.aligned_normal(s.author), pg_temp.aligned_normal(s.source_author)) AS same_author) a;
  CREATE TEMP TABLE aligned_title_map ON COMMIT DROP AS
  SELECT s.key, s.name, s.author, array_agg(c.title_id ORDER BY c.title_id) FILTER (WHERE c.title_id IS NOT NULL) AS ids
  FROM aligned_titles s
  LEFT JOIN aligned_title_candidates c ON c.key = s.key AND c.tier = (SELECT min(m.tier) FROM aligned_title_candidates m WHERE m.key = s.key)
  GROUP BY s.key, s.name, s.author;
  SELECT string_agg(name || ' / ' || author || CASE WHEN ids IS NULL THEN ' (not found)' ELSE ' (ambiguous)' END, '; ' ORDER BY name) INTO problems
  FROM aligned_title_map WHERE ids IS NULL OR cardinality(ids) > 1;
  IF problems IS NOT NULL THEN RAISE EXCEPTION 'Aligned demo preferences: unresolved titles: %', problems; END IF;

  CREATE TEMP TABLE aligned_requested ON COMMIT DROP AS
  SELECT cm.ids[1] AS club_id, tm.ids[1] AS title_id, r.rank
  FROM aligned_rows r
  JOIN aligned_club_map cm ON cm.club = r.club
  JOIN aligned_title_map tm ON tm.key = r.title_key;
  SELECT string_agg(DISTINCT club_id, ', ') INTO problems FROM (
    SELECT club_id FROM aligned_requested GROUP BY club_id, title_id HAVING count(*) > 1
    UNION SELECT club_id FROM aligned_requested GROUP BY club_id, rank HAVING count(*) > 1) d;
  IF problems IS NOT NULL THEN RAISE EXCEPTION 'Aligned demo preferences: duplicate titles or ranks for clubs: %', problems; END IF;

  -- Use the member who already holds the source ballot; otherwise the club leader, then the lowest member id.
  CREATE TEMP TABLE aligned_holders ON COMMIT DROP AS
  SELECT DISTINCT ON (club_id) club_id, person_id FROM (
    SELECT b.club_id, b.person_id, 0 AS source_order,
      -(SELECT count(*) FROM ballot_marks m WHERE m.cycle_id = b.cycle_id AND m.club_id = b.club_id AND m.person_id = b.person_id) AS weight
    FROM ballots b WHERE b.cycle_id = source_cycle
    UNION ALL
    SELECT m.club_id, m.person_id, 1, CASE WHEN m.leader THEN 0 ELSE 1 END
    FROM memberships m JOIN people p ON p.id = m.person_id WHERE p.role = 'member'
  ) h
  WHERE club_id IN (SELECT DISTINCT club_id FROM aligned_requested)
  ORDER BY club_id, source_order, weight, person_id;
  SELECT string_agg(DISTINCT c.name, '; ') INTO problems FROM aligned_requested r
  JOIN clubs c ON c.id = r.club_id WHERE NOT EXISTS (SELECT 1 FROM aligned_holders h WHERE h.club_id = r.club_id);
  IF problems IS NOT NULL THEN RAISE EXCEPTION 'Aligned demo preferences: clubs without a member to hold the ballot: %', problems; END IF;

  -- Slots are copied without assignments, so a drafted or published source starts collecting again.
  SELECT CASE WHEN status = 'open' THEN 'open' ELSE 'collecting' END INTO target_status FROM cycles WHERE id = source_cycle;
  INSERT INTO cycles (id, name, deadline, starts_on, ends_on, status)
  SELECT target_cycle, 'Demo preferences 2027 (aligned)', deadline, starts_on, ends_on, target_status FROM cycles WHERE id = source_cycle;
  INSERT INTO meeting_slots (id, cycle_id, club_id, month, meeting)
  SELECT gen_random_uuid()::text, target_cycle, club_id, month, meeting FROM meeting_slots WHERE cycle_id = source_cycle;
  INSERT INTO ballots (cycle_id, club_id, person_id) SELECT target_cycle, club_id, person_id FROM aligned_holders;
  INSERT INTO ballot_marks (cycle_id, club_id, person_id, title_id, mark, rank)
  SELECT target_cycle, r.club_id, h.person_id, r.title_id, 'selected', r.rank
  FROM aligned_requested r JOIN aligned_holders h ON h.club_id = r.club_id;

  SELECT count(*) INTO ballot_count FROM ballots WHERE cycle_id = target_cycle;
  SELECT count(*) INTO selection_count FROM ballot_marks WHERE cycle_id = target_cycle;
  SELECT count(*) INTO slot_count FROM meeting_slots WHERE cycle_id = target_cycle;
  DROP FUNCTION pg_temp.aligned_normal(text);
  RAISE NOTICE 'Created % with % ballots, % selections and % meeting slots.', target_cycle, ballot_count, selection_count, slot_count;
END
